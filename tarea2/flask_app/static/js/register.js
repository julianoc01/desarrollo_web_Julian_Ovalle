const poblarRegion = () => {
    let departmentSelect = document.getElementById("region");
    for (const department in data) {
      let option = document.createElement("option");
      option.value = department;
      option.text = department;
      departmentSelect.appendChild(option);
    }
    
  };


const updateComuna = () => {
    let departmentSelect = document.getElementById("region");
    let courseSelect = document.getElementById("comuna");
    
    let selectedDepartment = departmentSelect.value;
    
    courseSelect.innerHTML = "";
    
    if (data[selectedDepartment]) {
      data[selectedDepartment].forEach(course => {
        let option = document.createElement("option");
        option.value = course;
        option.text = course;
        courseSelect.appendChild(option);
      });
    }
  };
  
  document.getElementById("region").addEventListener("change", updateComuna);

  window.onload = () => {
    poblarRegion();
  };
  










const validateName = (name) => {
    if(!name) return false;
    let lengthValid = name.trim().length >= 4;
    return lengthValid;
}
const validatePhoneNumber = (phoneNumber) => {
    if (!phoneNumber) return false;
    // validación de longitud
    let lengthValid = phoneNumber.length >= 8;

    // validación de formato
    let re = /^[0-9]+$/;
    let formatValid = re.test(phoneNumber);

    // devolvemos la lógica AND de las validaciones.
    return lengthValid && formatValid;
};
const validateEmail = (email) => {
    if (!email) return false;
    let lengthValid = email.length > 15;

    // validamos el formato
    let re = /^[\w.]+@[a-zA-Z_]+?\.[a-zA-Z]{2,3}$/;
    let formatValid = re.test(email);

    // devolvemos la lógica AND de las validaciones.
    return lengthValid && formatValid;
};
const validateSelect = (select) => {
    if(!select) return false;
    return true
}
const validateComuna = (comuna) => {
    if(!comuna) return false;
    let lengthValid = comuna.trim().length >= 4;
    return lengthValid;
}
const validateContrasena = ( contasena,contasena2) => {
    if (contasena.length < 4 || contasena2.length< 4) return false
    if (!contasena || !contasena2) return false;
    if (contasena != contasena2) return false;
    return true
}


